def _chart_cumulative_returns(
    portfolio_returns: pd.Series,
    benchmark_returns: pd.Series,
    drawdown_periods: list,
) -> go.Figure:
    cum_port = (1 + portfolio_returns).cumprod() - 1
    cum_bench = (1 + benchmark_returns).cumprod() - 1

    fig = go.Figure()

    # Drawdown shading
    for dd in drawdown_periods:
        try:
            x0 = pd.Timestamp(dd["start"])
            x1 = pd.Timestamp(dd["end"])
            fig.add_vrect(
                x0=x0, x1=x1,
                fillcolor="rgba(255,68,68,0.10)",
                line_width=0,
                layer="below",
            )
        except Exception:
            pass

    fig.add_trace(go.Scatter(
        x=cum_port.index, y=cum_port.values * 100,
        name="Portfolio",
        line=dict(color="#2d88ff", width=2),
        mode="lines",
    ))
    fig.add_trace(go.Scatter(
        x=cum_bench.index, y=cum_bench.values * 100,
        name="SPY Benchmark",
        line=dict(color="#666666", width=1.5, dash="dash"),
        mode="lines",
    ))

    fig.update_layout(
        title="Cumulative Returns vs Benchmark",
        yaxis_ticksuffix="%",
        yaxis_title="Cumulative Return (%)",
        xaxis_title="Date",
        legend=dict(bgcolor="rgba(0,0,0,0)", borderwidth=0),
    )
    return _apply_dark(fig)


def _chart_monthly_heatmap(monthly_returns: dict) -> go.Figure:
    if not monthly_returns:
        fig = go.Figure()
        fig.update_layout(title="Monthly Returns (no data)")
        return _apply_dark(fig)

    years = sorted(monthly_returns.keys())
    months = [f"{m:02d}" for m in range(1, 13)]
    month_labels = ["Jan", "Feb", "Mar", "Apr", "May", "Jun",
                    "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"]

    z = []
    text = []
    for year in years:
        row_z = []
        row_text = []
        for m in months:
            val = monthly_returns[year].get(m, None)
            if val is None:
                row_z.append(None)
                row_text.append("")
            else:
                row_z.append(val * 100)
                sign = "+" if val > 0 else ""
                row_text.append(f"{sign}{val * 100:.1f}%")
        z.append(row_z)
        text.append(row_text)

    fig = go.Figure(go.Heatmap(
        z=z,
        x=month_labels,
        y=years,
        text=text,
        texttemplate="%{text}",
        colorscale=[
            [0.0, "#ff4444"],
            [0.5, "#1a1a2e"],
            [1.0, "#44ff88"],
        ],
        zmid=0,
        colorbar=dict(
            ticksuffix="%",
            bgcolor="#0d1117",
            outlinecolor="#1e2d3d",
            tickfont=dict(color="#dce8f0"),
        ),
        hovertemplate="<b>%{y} %{x}</b><br>Return: %{text}<extra></extra>",
    ))
    fig.update_layout(
        title="Monthly Returns",
        xaxis_title="Month",
        yaxis_title="Year",
    )
    return _apply_dark(fig)


def _chart_rolling_sharpe(rolling_sharpe_252d: list) -> go.Figure:
    fig = go.Figure()

    if rolling_sharpe_252d:
        dates = [pd.Timestamp(d["date"]) for d in rolling_sharpe_252d]
        sharpes = [d["sharpe"] for d in rolling_sharpe_252d]

        fig.add_trace(go.Scatter(
            x=dates, y=sharpes,
            name="Rolling Sharpe",
            line=dict(color="#2d88ff", width=2),
            mode="lines",
        ))

    # Reference lines
    for level, color, dash, label in [
        (0,   "#888888", "solid",  "0"),
        (0.5, "#ffcc44", "dash",   "0.5"),
        (1.0, "#44bb66", "dash",   "1.0"),
        (2.0, "#44ff88", "dash",   "2.0"),
    ]:
        fig.add_hline(
            y=level,
            line=dict(color=color, dash=dash, width=1),
            annotation_text=label,
            annotation_font_color=color,
            annotation_position="right",
        )

    fig.update_layout(
        title="Rolling 252-Day Sharpe Ratio",
        yaxis_title="Sharpe Ratio",
        xaxis_title="Date",
        legend=dict(bgcolor="rgba(0,0,0,0)"),
    )
    return _apply_dark(fig)


def _chart_hit_rate_by_sector(sector_hit_rates: dict) -> go.Figure:
    if not sector_hit_rates:
        fig = go.Figure()
        fig.update_layout(title="Win Rate by Sector (no data)")
        return _apply_dark(fig)

    items = sorted(
        sector_hit_rates.items(),
        key=lambda kv: kv[1].get("win_rate", 0),
        reverse=True,
    )
    sectors = [k.title() for k, _ in items]
    win_rates = [v.get("win_rate", 0) * 100 for _, v in items]
    counts = [v.get("trade_count", 0) for _, v in items]

    # Color gradient red → green based on win rate
    def _wr_color(wr: float) -> str:
        t = wr / 100.0
        r = int(255 * (1 - t))
        g = int(255 * t)
        return f"rgb({r},{g},68)"

    colors = [_wr_color(wr) for wr in win_rates]

    fig = go.Figure(go.Bar(
        x=sectors,
        y=win_rates,
        marker_color=colors,
        text=[f"{c} trades" for c in counts],
        textposition="outside",
        textfont=dict(color="#dce8f0", size=11),
        hovertemplate="<b>%{x}</b><br>Win Rate: %{y:.1f}%<extra></extra>",
    ))
    fig.update_layout(
        title="Win Rate by Sector",
        yaxis_title="Win Rate (%)",
        yaxis_range=[0, 110],
        xaxis_title="Sector",
    )
    return _apply_dark(fig)


def _chart_score_timeseries(
    score_timeseries: dict,
    trades: list,
) -> go.Figure:
    if not score_timeseries:
        fig = go.Figure()
        fig.update_layout(title="Reconstructed Score Timeseries (no data)")
        return _apply_dark(fig)

    # Rank sectors by trade count
    trade_counts: dict[str, int] = {}
    for t in trades:
        sector = t.get("sector") or t.get("node_id", "")
        trade_counts[sector] = trade_counts.get(sector, 0) + 1

    def _sector_key(node_id: str) -> int:
        return trade_counts.get(node_id, 0)

    sorted_nodes = sorted(score_timeseries.keys(), key=_sector_key, reverse=True)[:5]

    colors = ["#2d88ff", "#44ff88", "#ffcc44", "#ff8844", "#ff4444"]

    fig = go.Figure()
    for i, node_id in enumerate(sorted_nodes):
        pts = score_timeseries[node_id]
        if not pts:
            continue
        dates = [pd.Timestamp(p["date"]) for p in pts]
        scores = [p["score"] for p in pts]
        color = colors[i % len(colors)]

        fig.add_trace(go.Scatter(
            x=dates, y=scores,
            name=node_id.title(),
            line=dict(color=color, width=2),
            mode="lines",
        ))

        # Entry/exit markers from trades
        entry_dates, entry_scores, exit_dates, exit_scores = [], [], [], []
        for t in trades:
            sector = t.get("sector") or t.get("node_id", "")
            if sector != node_id:
                continue
            if "entry_date" in t:
                ed = pd.Timestamp(t["entry_date"])
                if dates:
                    closest = min(range(len(dates)), key=lambda j: abs(dates[j] - ed))
                    entry_dates.append(ed)
                    entry_scores.append(scores[closest])
            if "exit_date" in t:
                xd = pd.Timestamp(t["exit_date"])
                if dates:
                    closest = min(range(len(dates)), key=lambda j: abs(dates[j] - xd))
                    exit_dates.append(xd)
                    exit_scores.append(scores[closest])

        if entry_dates:
            fig.add_trace(go.Scatter(
                x=entry_dates, y=entry_scores,
                name=f"{node_id.title()} Entry",
                mode="markers",
                marker=dict(symbol="triangle-up", size=10, color=color),
                showlegend=False,
            ))
        if exit_dates:
            fig.add_trace(go.Scatter(
                x=exit_dates, y=exit_scores,
                name=f"{node_id.title()} Exit",
                mode="markers",
                marker=dict(symbol="triangle-down", size=10, color=color),
                showlegend=False,
            ))

    fig.update_layout(
        title="Reconstructed Score Timeseries",
        yaxis_title="Score",
        xaxis_title="Date",
        legend=dict(bgcolor="rgba(0,0,0,0)"),
    )
    return _apply_dark(fig)


def _chart_regime_distribution(
    portfolio_returns: pd.Series,
    regime_returns: dict,
) -> go.Figure:
    fig = go.Figure()

    if not regime_returns:
        fig.add_annotation(
            text="Regime data not available",
            xref="paper", yref="paper",
            x=0.5, y=0.5,
            showarrow=False,
            font=dict(color="#6b8099", size=14),
        )
        fig.update_layout(title="Macro Regime Distribution (no data)")
        return _apply_dark(fig)

    regime_colors = {
        "RISK_ON":  "#44ff88",
        "NEUTRAL":  "#888888",
        "RISK_OFF": "#ff8844",
        "CRISIS":   "#ff4444",
    }

    # Build quarterly bins from portfolio_returns index
    if not portfolio_returns.empty:
        dates = portfolio_returns.index
        quarters = pd.period_range(dates[0], dates[-1], freq="Q")
        n = len(quarters)
        regimes = list(regime_returns.keys())
        total_count = sum(v.get("trade_count", 1) for v in regime_returns.values())
        if total_count == 0:
            total_count = 1

        q_dates = [q.start_time for q in quarters]

        for regime in regimes:
            fraction = regime_returns[regime].get("trade_count", 0) / total_count
            fig.add_trace(go.Scatter(
                x=q_dates,
                y=[fraction] * n,
                name=regime,
                mode="lines",
                stackgroup="one",
                fillcolor=regime_colors.get(regime, "#888888"),
                line=dict(color=regime_colors.get(regime, "#888888"), width=0),
                hovertemplate=f"<b>{regime}</b><br>Fraction: %{{y:.1%}}<extra></extra>",
            ))
    else:
        fig.add_annotation(
            text="No portfolio return data",
            xref="paper", yref="paper",
            x=0.5, y=0.5, showarrow=False,
            font=dict(color="#6b8099", size=14),
        )

    fig.update_layout(
        title="Macro Regime Distribution",
        yaxis_title="Fraction of Days",
        xaxis_title="Date",
        yaxis_tickformat=".0%",
        legend=dict(bgcolor="rgba(0,0,0,0)"),
    )
    return _apply_dark(fig)


def _chart_drawdown_table(drawdown_periods: list) -> go.Figure:
    top = drawdown_periods[:10]

    if not top:
        fig = go.Figure()
        fig.update_layout(title="Top Drawdown Periods (no data)")
        return _apply_dark(fig)

    ranks = list(range(1, len(top) + 1))
    starts = [d.get("start", "") for d in top]
    ends   = [d.get("end", "") for d in top]
    depths = [f'{d.get("depth", 0) * 100:.1f}%' for d in top]
    recoveries = [str(d.get("recovery_days", "—")) for d in top]

    # Alternating row colors
    fill_colors = []
    for i in range(len(top)):
        fill_colors.append("#0d1117" if i % 2 == 0 else "#111722")

    fig = go.Figure(go.Table(
        header=dict(
            values=["<b>Rank</b>", "<b>Start</b>", "<b>End</b>",
                    "<b>Depth</b>", "<b>Recovery Days</b>"],
            fill_color="#1e2d3d",
            font=dict(color="#dce8f0", size=12),
            line_color="#2d3d4d",
            align="center",
        ),
        cells=dict(
            values=[ranks, starts, ends, depths, recoveries],
            fill_color=[fill_colors] * 5,
            font=dict(color=["#dce8f0", "#dce8f0", "#dce8f0", "#ff6666", "#dce8f0"], size=11),
            line_color="#1e2d3d",
            align=["center", "center", "center", "center", "center"],
        ),
    ))
    fig.update_layout(title="Top 10 Drawdown Periods")
    return _apply_dark(fig)


