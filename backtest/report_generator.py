def _apply_dark(fig: go.Figure) -> go.Figure:
    fig.update_layout(**DARK)
    return fig


def _fig_to_html(fig: go.Figure, first: bool = False) -> str:
    include_js = True if first else False
    return pio.to_html(
        fig,
        include_plotlyjs=include_js,
        full_html=False,
        config={"displayModeBar": False},
    )


def _pct(val: float) -> str:
    sign = "+" if val > 0 else ""
    return f"{sign}{val * 100:.1f}%"


def _metric_card(label: str, value_html: str) -> str:
    return (
        f'<div class="metric-card">'
        f'<div class="label">{label}</div>'
        f'<div class="value">{value_html}</div>'
        f"</div>"
    )


def _colored_pct(val: float, always_red: bool = False) -> str:
    if always_red:
        cls = "negative"
    elif val > 0:
        cls = "positive"
    else:
        cls = "negative"
    return f'<span class="{cls}">{_pct(val)}</span>'


def _sharpe_color(val: float) -> str:
    if val >= 1.0:
        cls = "positive"
    elif val >= 0.5:
        cls = "yellow"
    else:
        cls = "negative"
    return f'<span class="{cls}">{val:.2f}</span>'


