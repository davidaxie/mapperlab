def _write_summary_md(
    metrics: dict,
    output_dir: Path,
    start_date: str,
    end_date: str,
    initial_capital: float,
    benchmark_returns: pd.Series,
) -> None:
    total_return = metrics.get("total_return", 0)
    ann_return   = metrics.get("annualized_return", 0)
    sharpe       = metrics.get("sharpe", 0)
    sortino      = metrics.get("sortino", 0)
    calmar       = metrics.get("calmar", 0)
    max_dd       = metrics.get("max_drawdown", 0)
    win_rate     = metrics.get("win_rate", 0)
    total_trades = metrics.get("total_trades", 0)

    bench_cum  = (1 + benchmark_returns).prod() - 1 if not benchmark_returns.empty else 0
    n_years    = len(benchmark_returns) / 252 if not benchmark_returns.empty else 1
    bench_ann  = (1 + bench_cum) ** (1 / max(n_years, 0.001)) - 1

    benchmark_total = metrics.get("benchmark_total_return", bench_cum)
    bench_ann_met   = metrics.get("benchmark_annualized_return", bench_ann)

    dd_periods = metrics.get("drawdown_periods", [])
    dd_rows = ""
    for i, dd in enumerate(dd_periods[:5], 1):
        depth = dd.get("depth", 0)
        dd_rows += (
            f"| {i} | {dd.get('start', '')} | {dd.get('end', '')} "
            f"| {depth * 100:.1f}% | {dd.get('recovery_days', '—')} days |\n"
        )

    md = f"""# MapperLab Backtest Summary

**Period:** {start_date} \u2192 {end_date}
**Initial Capital:** ${initial_capital:,.0f}

## Performance

| Metric | Strategy | Benchmark |
|--------|----------|-----------|
| Total Return | {total_return:.1%} | {benchmark_total:.1%} |
| Annualized Return | {ann_return:.1%} | {bench_ann_met:.1%} |
| Sharpe Ratio | {sharpe:.2f} | \u2014 |
| Sortino Ratio | {sortino:.2f} | \u2014 |
| Calmar Ratio | {calmar:.2f} | \u2014 |
| Max Drawdown | {max_dd:.1%} | \u2014 |
| Win Rate | {win_rate:.1%} | \u2014 |
| Total Trades | {total_trades} | \u2014 |

## Top Drawdown Periods

| Rank | Start | End | Depth | Recovery |
|------|-------|-----|-------|----------|
{dd_rows}
*Generated by MapperLab Backtest Engine*
"""
    (output_dir / "summary.md").write_text(md, encoding="utf-8")


# ---------------------------------------------------------------------------
# Main entry point
# ---------------------------------------------------------------------------

def generate(
    metrics: dict,
    portfolio_returns: pd.Series,
    benchmark_returns: pd.Series,
    score_timeseries: dict,   # node_id -> [{date, score}, ...]
    trades: list,
    output_dir: str | Path,
    start_date: str,
    end_date: str,
    initial_capital: float,
) -> None:
    """
    Generate full backtest report to output_dir/report.html.
    Also writes output_dir/metrics.json and output_dir/summary.md.
    """
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    # ---- metrics.json -------------------------------------------------------
    (output_dir / "metrics.json").write_text(
        json.dumps(metrics, indent=2, default=str),
        encoding="utf-8",
    )

    # ---- summary.md ---------------------------------------------------------
    _write_summary_md(metrics, output_dir, start_date, end_date, initial_capital, benchmark_returns)

    # ---- Build charts -------------------------------------------------------
    drawdown_periods = metrics.get("drawdown_periods", [])
    monthly_returns  = metrics.get("monthly_returns", {})
    rolling_sharpe   = metrics.get("rolling_sharpe_252d", [])
    sector_hit_rates = metrics.get("sector_hit_rates", {})
    regime_returns   = metrics.get("regime_returns", {})

    chart_figs = [
        _chart_cumulative_returns(portfolio_returns, benchmark_returns, drawdown_periods),
        _chart_monthly_heatmap(monthly_returns),
        _chart_rolling_sharpe(rolling_sharpe),
        _chart_hit_rate_by_sector(sector_hit_rates),
        _chart_score_timeseries(score_timeseries, trades),
        _chart_regime_distribution(portfolio_returns, regime_returns),
        _chart_drawdown_table(drawdown_periods),
    ]

    charts_html = []
    for i, fig in enumerate(chart_figs):
        charts_html.append(_fig_to_html(fig, first=(i == 0)))

    # ---- Metrics cards HTML -------------------------------------------------
    metrics_cards_html = _build_metrics_cards(metrics)

    # ---- Render Jinja2 template ---------------------------------------------
    generated_at = datetime.now().strftime("%Y-%m-%d %H:%M UTC")
    template = Template(REPORT_TEMPLATE)
    html = template.render(
        start_date=start_date,
        end_date=end_date,
        initial_capital=initial_capital,
        metrics_cards_html=metrics_cards_html,
        charts=charts_html,
        generated_at=generated_at,
    )

    (output_dir / "report.html").write_text(html, encoding="utf-8")


