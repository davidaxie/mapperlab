def _build_metrics_cards(metrics: dict) -> str:
    cards = []

    # Total Return
    tr = metrics.get("total_return", 0)
    cards.append(_metric_card("Total Return", _colored_pct(tr)))

    # Annualized Return
    ar = metrics.get("annualized_return", 0)
    cards.append(_metric_card("Ann. Return", _colored_pct(ar)))

    # Sharpe Ratio
    sharpe = metrics.get("sharpe", 0)
    cards.append(_metric_card("Sharpe Ratio", _sharpe_color(sharpe)))

    # Max Drawdown
    mdd = metrics.get("max_drawdown", 0)
    cards.append(_metric_card("Max Drawdown", _colored_pct(mdd, always_red=True)))

    # Win Rate
    wr = metrics.get("win_rate", 0)
    cards.append(_metric_card("Win Rate", _colored_pct(wr)))

    # Total Trades
    tt = metrics.get("total_trades", 0)
    cards.append(_metric_card("Total Trades", f'<span class="neutral">{tt}</span>'))

    # Sortino
    sortino = metrics.get("sortino", 0)
    cards.append(_metric_card("Sortino", _sharpe_color(sortino)))

    # Calmar
    calmar = metrics.get("calmar", 0)
    cards.append(_metric_card("Calmar", _sharpe_color(calmar)))

    return "\n    ".join(cards)


